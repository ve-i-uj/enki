"""Модуль для преобразования различных типов данных.

Модуль предоставляет набор функций для преобразования:
- углов между целочисленным 8-битным представлением и радианами
- IP-адресов между строковым и целочисленным представлением
- номеров портов между сетевым и хостовым порядком байт
"""

import math
import socket
import struct


def int82angle(angle: int) -> float:
    """Преобразует 8-битное целое число в угол в радианах.

    Args:
        angle (int): Целое число в диапазоне [-128, 127], представляющее угол.

    Returns:
        float: Угол в радианах, вычисленный как π * angle / 128.

    """
    return math.pi * float(angle) / 128


def angle2int8(angle: float) -> int:
    """Преобразует угол в радианах в 8-битное целое число.

    Args:
        angle (float): Угол в радианах.

    Returns:
        int: Целое число в диапазоне [-128, 127], представляющее угол,
             вычисленное как round(angle * 128 / π).

    """
    return int(angle * 128 / math.pi + 0.5)


def ip2int(addr: str) -> int:
    """Преобразует строку с IP-адресом в 32-битное целое число.

    Args:
        addr (str): Строка с IPv4 адресом (например, '192.168.0.1').

    Returns:
        int: Целое число, представляющее IP-адрес.

    """
    return struct.unpack("I", socket.inet_aton(addr))[0]


def int2ip(addr: int) -> str:
    """Преобразует 32-битное целое число в строку с IP-адресом.

    Args:
        addr (int): Целое число, представляющее IP-адрес.

    Returns:
        str: Строка с IPv4 адресом (например, '192.168.0.1').

    """
    return socket.inet_ntoa(struct.pack("I", addr))


def int2port(uint16_port: int) -> int:
    """Преобразует 16-битное целое число из сетевого порядка байт в хостовый.

    Args:
        uint16_port (int): 16-битное целое число в сетевом порядке байт.

    Returns:
        int: Номер порта в хостовом порядке байт.

    """
    return socket.ntohs(uint16_port)


def port2int(port: int) -> int:
    """Преобразует номер порта в 16-битное целое число в сетевом порядке байт.

    Args:
        port (int): Номер порта в хостовом порядке байт.

    Returns:
        int: 16-битное целое число в сетевом порядке байт.

    """
    return socket.htons(port)
